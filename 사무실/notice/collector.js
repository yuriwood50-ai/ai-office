// A단계(수집): 기관 게시판을 점검해서 공고 후보를 모아요. 이 파일에는 AI를 부르는 코드가 없어요(모델 클라이언트를 받는 자리도 없음).
//  - 점검 결과는 6가지로 나눠 기록해요. '신규 없음'은 정상으로 읽었을 때만 써요.
//  - 새 공고는 신규/수정/마감 연장/재공고/후보 중복으로 가려내고, 과거에 놓친 공고는 누락 기록을 남겨요.
'use strict';
const { 공고만들기, 분류하기, 규칙적용 } = require('./differ');
const { 새ID } = require('./store');
const { 한국날짜 } = require('./deadline');

const 결과 = {
  없음: '정상 완료·신규 없음', 발견: '정상 완료·신규 발견', 접속실패: '접속 실패',
  추출실패: '자료 추출 실패', 검증필요: '검증 필요', 미실행: '검색 미실행',
};
const 다시확인대상 = [결과.접속실패, 결과.추출실패, 결과.검증필요, 결과.미실행];
const 심각도 = [결과.접속실패, 결과.추출실패, 결과.검증필요, 결과.미실행, 결과.발견, 결과.없음];

function 누락기록만들기(공고, 기관, { 이전실행들, 재확인, 지금, 실행ID }) {
  const 마감후 = 공고.공고상태 === '접수 마감';
  const 게시 = 공고.게시일 || null;
  if (!재확인 && !이전실행들.length) return null; // 첫 점검은 기준선이라 '놓친 것'이 아니에요
  // 날짜 단위로만 알 수 있어서, 올라온 '다음 날 이후'의 점검만 놓친 근거로 삼아요 (같은 날 올라온 글을 오탐하지 않으려고)
  const 창 = 이전실행들.filter((r) => !게시 || 한국날짜(new Date(r.시작)) > 게시);
  if (!재확인 && !마감후 && (!게시 || !창.length)) return null; // 올라온 뒤 첫 점검이면 놓친 게 아니에요
  const 기관결과 = 창.map((r) => ({ 실행ID: r.id, 시각: r.시작, 기관결과: (r.결과 || []).filter((x) => x.기관ID === 기관.id).map((x) => x.결과).join(', ') || '이 실행에 포함되지 않음' }));
  let 원인 = '원인 확인 불가', 근거 = '기록만으로는 원인을 알 수 없어요';
  if (기관결과.some((x) => 다시확인대상.slice(0, 3).some((k) => x.기관결과.includes(k)))) {
    원인 = '해당 기관 점검 실패'; 근거 = '게시된 뒤의 점검에서 이 기관이 접속 실패·추출 실패·검증 필요였어요';
  } else if (기관결과.some((x) => x.기관결과.includes(결과.미실행) || x.기관결과 === '이 실행에 포함되지 않음')) {
    원인 = '해당 기관 점검 안 함'; 근거 = '게시된 뒤의 실행에서 이 기관을 점검하지 않았어요';
  } else if (!창.length) {
    근거 = '게시일 이후의 점검 기록이 없어서 원인을 알 수 없어요';
  }
  return {
    id: 새ID('m'), 공고ID: 공고.id, 공고명: 공고.공고명, 기관ID: 기관.id, 기관명: 기관.이름,
    원래게시일: 게시 || '미확인', 최초발견일: 한국날짜(지금), 최초발견실행: 실행ID,
    누락된실행: 기관결과, 추정원인: 원인, 근거, 마감후발견: 마감후, 재확인,
    재발방지조치: 원인 === '해당 기관 점검 실패' ? '다시 확인할 기관 목록에서 재점검' : 원인 === '해당 기관 점검 안 함' ? '다음 점검에 이 기관 포함' : '없음 (원인 확인 불가)',
  };
}

// 글 한 건을 받아 저장해요. 돌려주는 값: { 종류, 공고 }
function 들이기({ store, 목록, 항목, 기관, 설정, 지금, 실행, 이전실행들, 재확인, 원천 }) {
  const 후보 = 공고만들기(항목, 기관, { 시각: 지금.toISOString(), 실행ID: 실행.id, 원천 });
  if (!후보.공고명 || !/^https?:\/\//i.test(후보.공식링크)) return { 종류: '건너뜀', 이유: '공고명 또는 공식 링크가 없어요' };
  const 판 = 분류하기(목록, 후보);
  const 변경기록 = (n) => 판.변경.forEach((c) => n.변경이력.push({ 시각: 지금.toISOString(), 실행ID: 실행.id, ...c }));
  if (판.종류 === '기존') { 실행.지표.기존 = (실행.지표.기존 || 0) + 1; return { 종류: '기존', 공고: 판.대상 }; }
  if (판.종류 === '수정' || 판.종류 === '마감 연장') {
    const n = 판.대상;
    변경기록(n);
    n.공고명 = 후보.공고명;
    if (후보.접수마감.원문표기 !== n.접수마감.원문표기) { n.접수마감 = 후보.접수마감; if (후보.접수시작.날짜) n.접수시작 = 후보.접수시작; }
    if (후보.원문.본문) n.원문 = 후보.원문;
    n.첨부 = 후보.첨부;
    n.공고상태 = 판.종류;
    규칙적용(n, { 기관, 설정, 지금 });
    store.공고저장(n);
    return { 종류: 판.종류, 공고: n };
  }
  if (판.종류 === '재공고') {
    후보.공고상태 = '재공고'; 후보.연결 = { 재공고원본ID: 판.대상.id }; 변경기록(후보);
    판.대상.연결 = { ...판.대상.연결, 다음공고ID: 후보.id };
    판.대상.변경이력.push({ 시각: 지금.toISOString(), 실행ID: 실행.id, 항목: '재공고됨', 이전: '', 이후: `새 공고 ${후보.id}` });
    store.공고저장(판.대상);
  } else if (판.종류 === '후보중복') {
    후보.중복후보 = 판.대상.id;
  }
  규칙적용(후보, { 기관, 설정, 지금 });
  if (후보.공고상태 === '접수 마감' && 판.종류 === '재공고') 후보.공고상태 = '접수 마감';
  store.공고새로(후보);
  목록.push(후보);
  const 누락 = 누락기록만들기(후보, 기관, { 이전실행들, 재확인, 지금, 실행ID: 실행.id });
  if (누락) { store.누락추가(누락); 실행.누락기록수 = (실행.누락기록수 || 0) + 1; }
  return { 종류: 판.종류, 공고: 후보, 누락: !!누락 };
}

// fetcher.fetchBoard(기관, 게시판, { 회차, 지금 }) -> { http, items: [...] | null }  (실패하면 { kind, http } 를 던져요)
async function 수집({ store, 설정, fetcher, 모드, 지금 = new Date(), 기관ID목록, 재확인 = false, 중지 = () => false, 원천 = '공식게시판' }) {
  const 기관들 = store.기관목록();
  const 대상 = 기관ID목록?.length ? 기관ID목록.map((id) => 기관들.find((k) => k.id === id)).filter(Boolean) : 기관들.filter((k) => k.사용);
  const 이전실행들 = store.실행목록().filter((r) => r.종류 === '수집' || r.종류 === '재확인');
  const 실행 = { id: 새ID('r'), 종류: 재확인 ? '재확인' : '수집', 단계: 'A', 모드, 시작: 지금.toISOString(), 종료: null, 결과: [], 지표: {}, AI호출: { 횟수: 0 }, 중단이유: null };
  const 목록 = store.공고목록();
  const 시작ms = Date.now();
  const 지표 = { 대상기관: 대상.length, 완료: 0, 접속실패: 0, 추출실패: 0, 검증필요: 0, 미실행: 0, 신규: 0, 변경: 0, 중복후보: 0, 건너뜀: 0, 기존: 0 };
  실행.지표 = 지표; // 들이기()가 같은 객체에 '기존' 개수를 더해요

  for (const 기관 of 대상) {
    const 기관결과들 = [];
    for (const 판 of 기관.게시판) {
      const 기록 = { 기관ID: 기관.id, 기관명: 기관.이름, 게시판ID: 판.id, 주소: 판.주소, 결과: null, HTTP상태: null, 가져온글수: 0, 신규수: 0, 변경수: 0, 소요ms: 0, 오류: null };
      기관결과들.push(기록); 실행.결과.push(기록);
      if (중지()) { 기록.결과 = 결과.미실행; 기록.오류 = '작가님이 중지했어요'; 지표.미실행++; 실행.중단이유 = '작가님이 중지했어요'; continue; }
      if (!기관.사용) { 기록.결과 = 결과.미실행; 기록.오류 = '기관이 중지 상태예요'; 지표.미실행++; continue; }
      const t0 = Date.now();
      const 회차 = 이전실행들.filter((r) => (r.결과 || []).some((x) => x.기관ID === 기관.id && x.게시판ID === 판.id)).length;
      let 응답;
      try { 응답 = await fetcher.fetchBoard(기관, 판, { 회차, 지금 }); }
      catch (e) {
        기록.결과 = 결과.접속실패; 기록.HTTP상태 = e.http ?? null; 기록.오류 = e.kind === 'robots' ? `자동 확인 제한: ${e.message}` : e.kind === 'notimplemented' ? e.message : `${e.kind || '오류'}: ${e.message}`; 기록.소요ms = Date.now() - t0; 지표.접속실패++;
        continue;
      }
      기록.HTTP상태 = 응답.http ?? null;
      if (!Array.isArray(응답.items)) { 기록.결과 = 결과.추출실패; 기록.오류 = 응답.추출오류 || '게시판 목록을 해석하지 못했어요'; 기록.소요ms = Date.now() - t0; 지표.추출실패++; continue; }
      기록.가져온글수 = 응답.items.length;
      const 평소 = store.스냅샷목록(기관.id).filter((s) => s.게시판ID === 판.id).slice(-3);
      const 평균 = 평소.length ? 평소.reduce((a, s) => a + s.항목.length, 0) / 평소.length : 0;
      const 급감 = 평균 >= 5 && 응답.items.length < 평균 * 0.3;
      for (const 항목 of 응답.items) {
        const r = 들이기({ store, 목록, 항목: { ...항목, 지역: 항목.지역 }, 기관, 설정, 지금, 실행, 이전실행들, 재확인, 원천 });
        if (r.종류 === '건너뜀') 지표.건너뜀++;
        else if (['신규', '재공고', '후보중복'].includes(r.종류)) { 기록.신규수++; 지표.신규++; if (r.종류 === '후보중복') 지표.중복후보++; }
        else if (['수정', '마감 연장'].includes(r.종류)) { 기록.변경수++; 지표.변경++; }
      }
      기록.범위 = 응답.범위 || null;
      if (급감 || 응답.부분확인) { 기록.결과 = 결과.검증필요; 기록.오류 = 응답.추출오류 || `평소 약 ${Math.round(평균)}건인데 ${응답.items.length}건만 읽혔어요`; 지표.검증필요++; }
      else {
        기록.결과 = 기록.신규수 ? 결과.발견 : 결과.없음; 지표.완료++;
        store.스냅샷저장(기관.id, 응답.items.map((x) => ({ 제목: x.제목, 링크: x.링크, 게시일: x.게시일 || null })), 지금.getTime(), 판.id);
      }
      기록.소요ms = Date.now() - t0;
    }
    기관.마지막점검 = 기관결과들.reduce((w, x) => (심각도.indexOf(x.결과) < 심각도.indexOf(w.결과) ? x : w), 기관결과들[0]);
    기관.마지막점검 = { 결과: 기관.마지막점검.결과, 시각: 지금.toISOString(), 건수: 기관결과들.reduce((a, x) => a + x.가져온글수, 0), HTTP상태: 기관.마지막점검.HTTP상태, 오류: 기관.마지막점검.오류, 실행ID: 실행.id };
  }
  store.기관저장(기관들);
  실행.종료 = new Date(지금.getTime() + (Date.now() - 시작ms)).toISOString();
  지표.소요ms = Date.now() - 시작ms; 지표.누락기록 = 실행.누락기록수 || 0;
  실행.지표 = 지표;
  if (재확인) 실행.안내 = '게시판에서 이미 내려간 글은 다시 찾을 수 없어요. 지금 게시판에 남아 있는 글만 비교해요.';
  store.실행저장(실행);
  return 실행;
}

// 직접 등록 / 가져오기 한 건: 수집과 똑같이 신규·중복·수정을 가려요.
function 직접등록({ store, 설정, 항목, 기관, 지금 = new Date(), 모드, 원천 = '직접등록' }) {
  const 실행 = { id: 새ID('r'), 종류: '등록', 단계: 'A', 모드, 시작: 지금.toISOString(), 종료: 지금.toISOString(), 결과: [], 지표: {}, AI호출: { 횟수: 0 } };
  const 목록 = store.공고목록();
  const r = 들이기({ store, 목록, 항목, 기관, 설정, 지금, 실행, 이전실행들: [], 재확인: false, 원천 });
  실행.지표 = { 종류: r.종류 };
  store.실행저장(실행);
  return r;
}

module.exports = { 수집, 직접등록, 들이기, 결과, 다시확인대상 };
