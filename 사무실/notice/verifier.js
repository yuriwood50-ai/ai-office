// AI 응답 검사와 반영 (코드): AI가 준 값은 '근거 문장이 원문에 실제로 있을 때만' 원문확인으로 인정해요.
'use strict';
const { 마감읽기 } = require('./deadline');
const { 본문정규화 } = require('./differ');

const 근거최대자 = 120, 값최대자 = 300;
const 판정값 = ['적합', '확인 필요', '부적합'];
const 글칸 = [['대상', '대상'], ['장소', '장소'], ['시간대', '시간대'], ['금액', '금액'], ['제출서류', '제출서류'], ['접수방법', '접수방법']];
const 압축 = (s) => 본문정규화(s).replace(/\s+/g, '');

class 응답오류 extends Error { constructor(kind, message) { super(message); this.kind = kind; } }

// 배치 응답 하나를 검사해요. 전체가 출력 상한을 넘으면 던지고(재시도하지 않아요), 공고별 위반은 그 공고만 오류로 표시해요.
function 응답검사(resp, 배치, 한도) {
  if (!resp || typeof resp !== 'object' || !Array.isArray(resp.결과)) throw new 응답오류('schema', '응답 형식이 올바르지 않아요');
  const 글자 = JSON.stringify(resp).length;
  if (글자 > 한도.호출출력자) throw new 응답오류('length', `응답이 출력 상한을 넘었어요 (${글자}자 > ${한도.호출출력자}자)`);
  const 공고당상한 = Math.max(300, Math.floor(한도.호출출력자 / Math.max(1, 한도.배치)));
  const 맵 = new Map();
  for (const id of 배치.map((p) => p.id)) 맵.set(id, { 오류: '응답에 이 공고가 없어요' });
  for (const r of resp.결과) {
    if (!r || !맵.has(r.id)) continue;
    const 크기 = JSON.stringify(r).length;
    if (크기 > 공고당상한) { 맵.set(r.id, { 오류: `공고당 응답 상한을 넘었어요 (${크기}자)` }); continue; }
    const 칸들 = Object.values(r.필드 || {});
    if (칸들.some((c) => c && ((c.근거 || '').length > 근거최대자 || String(c.값 ?? '').length > 값최대자))) { 맵.set(r.id, { 오류: '필드 값이나 근거 문장이 길이 상한을 넘었어요' }); continue; }
    if (r.적합도 && !판정값.includes(r.적합도.판정)) { 맵.set(r.id, { 오류: '적합도 판정 값이 올바르지 않아요' }); continue; }
    맵.set(r.id, { 결과: r });
  }
  return 맵;
}

const 근거있나 = (본문, 칸) => !!(칸 && 칸.근거 && 칸.값 !== undefined && 칸.값 !== null && 압축(본문).includes(압축(칸.근거)) && 압축(칸.근거).includes(압축(String(칸.값))));
const 짧게 = (arr) => (Array.isArray(arr) ? arr.filter((x) => typeof x === 'string').slice(0, 5).map((x) => x.slice(0, 근거최대자)) : []);

// AI 결과를 공고에 반영해요. 출처: 'AI'(방금 호출) | '재사용'(저장된 결과)
function 적용하기(n, 결과, { 출처, 키, 모드, 설정, 잘림, 지금 }) {
  const 본문 = [n.원문?.본문 || '', ...(n.첨부 || []).filter(a => a.상태 === '확인').map(a => a.본문 || '')].join('\n');
  const 필드 = 결과.필드 || {};
  for (const [칸, 키이름] of 글칸) {
    const c = 필드[칸]; if (!c || c.값 === null || c.값 === undefined || c.값 === '') continue;
    const 맞음 = 근거있나(본문, c);
    n[키이름] = String(c.값).slice(0, 값최대자);
    n.필드상태[칸] = 맞음 ? '원문확인' : 'AI추정';
    if (맞음) n.출처필드[칸] = c.근거;
  }
  if (필드.자격?.값) {
    const 맞음 = 근거있나(본문, 필드.자격);
    n.자격 = { 원문: String(필드.자격.값).slice(0, 값최대자), 조건: [String(필드.자격.값).slice(0, 값최대자)] };
    n.필드상태.자격 = 맞음 ? '원문확인' : 'AI추정'; if (맞음) n.출처필드.자격 = 필드.자격.근거;
  }
  if (필드.분야?.값 && ['A', 'B', 'C'].includes(필드.분야.값)) { n.분야 = 필드.분야.값; n.필드상태.분야 = 근거있나(본문, 필드.분야) ? '원문확인' : 'AI추정'; }
  const 추가확인 = [];
  const 마 = 필드.접수마감;
  if (마 && 마.값) {
    const 읽음 = 마감읽기(마.근거);
    if (압축(본문).includes(압축(마.근거 || '___')) && 읽음.날짜 === 마.값 && 읽음.마감판정 === '확정') {
      // 게시판에 적힌 원래 표기는 그대로 둬요 (다음 점검 때 '바뀌었나'를 비교하는 기준이에요). 근거 문장은 출처필드에 따로 남겨요.
      const 원래표기 = n.접수마감.원문표기 && n.접수마감.원문표기 !== '미확인' ? n.접수마감.원문표기 : 읽음.원문표기;
      n.접수마감 = { ...읽음, 원문표기: 원래표기, 판정근거: '원문 근거 문장에서 코드가 날짜를 읽어 확인했어요' };
      if (읽음.시작날짜) n.접수시작 = { 날짜: 읽음.시작날짜, 원문표기: 읽음.원문표기 };
      n.필드상태.접수마감 = '원문확인'; n.출처필드.접수마감 = 마.근거;
    } else {
      n.필드상태.접수마감 = 'AI추정';
      추가확인.push('AI가 알려준 마감일이 원문 근거와 맞지 않아서 반영하지 않았어요 (AI추정)');
    }
  }
  const 적 = 결과.적합도 || {};
  n.AI적합도 = { 판정: 판정값.includes(적.판정) ? 적.판정 : '확인 필요', 미충족: 짧게(적.미충족), 확인필요: [...짧게(적.확인필요), ...추가확인], 근거: 짧게(적.근거) };
  if (n.AI적합도.판정 === '적합' && (n.필드상태.대상 !== '원문확인')) n.AI적합도.확인필요.push('모집 대상을 원문에서 확인하지 못했어요');
  if (잘림) n.AI적합도.확인필요.push('본문이 길어서 앞부분만 검토했어요 (필수 항목이 뒤에 있을 수 있어요)');

  const 공식 = 모드 === 'mock' || n.원문?.공식확인 === true;
  const 첨부완료 = 모드 === 'mock' || ['확인', '없음'].includes(n.원문?.첨부확인);
  if (!공식) n.AI적합도.확인필요.push('공식 원문을 직접 확보한 기록이 없어요.');
  if (!첨부완료) n.AI적합도.확인필요.push('첨부의 지원 조건을 확인하지 못했어요.');
  const 필수 = 공식 && 첨부완료 && !n.원문?.본문잘림 && n.필드상태.대상 === '원문확인' && ['확정', '해당없음'].includes(n.접수마감.마감판정) && !!n.공식링크 && !!n.공고명 && !!n.기관명 && !잘림;
  n.검증상태 = 필수 ? '검증됨' : '원문확인됨';
  n.마지막검증 = 지금.toISOString();
  n.검증필요 = null;
  const 이전판 = n.검증기록?.판정버전;
  n.검증기록 = {
    검증키: 키, 검증시각: 지금.toISOString(), 결과출처: 출처, 모드, 본문잘림: !!잘림,
    판정버전: 출처 === '재사용' && 이전판 ? 이전판 : { 판정규칙: 설정.버전.판정규칙, 내조건: 설정.버전.내조건 },
  };
  return n;
}

module.exports = { 응답검사, 적용하기, 응답오류, 근거있나 };
