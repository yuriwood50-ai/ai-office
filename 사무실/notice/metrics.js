// 화면용 요약과 품질 지표. 지표마다 '측정 / 추정 / 조회 불가'를 꼭 구분해서 적어요. (AI가 말하는 신뢰도 % 같은 건 쓰지 않아요)
'use strict';
const { 마감상태, 한국날짜 } = require('./deadline');
const { 다시확인대상 } = require('./collector');

const 지원상태목록 = ['관심', '검토 중', '지원 준비', '지원 완료', '결과 대기', '선정', '미선정', '보류'];

function 요약(n, 지금) {
  const 마감 = 마감상태(n.접수마감, 지금);
  const ep = n['제외·보존'];
  return {
    id: n.id, 공고명: n.공고명, 기관명: n.기관명, 지역: n.지역, 우선순위: n.우선순위, 분야: n.분야, 검색종류: n.검색종류 || 'instructor', 주택: n.검색종류 === 'housing' ? require('./housing').주택분류(n) : null,
    마감날짜: n.접수마감.날짜, 마감시각: n.접수마감.시각, 마감표기: n.접수마감.원문표기, 마감판정: n.접수마감.마감판정, 남은일수: 마감.남은일수,
    판정: n.적합도.판정, 검증상태: n.검증상태, 공고상태: n.공고상태, 지원상태: n.지원상태 || '',
    노출: ep.추천노출.노출, 노출사유: ep.추천노출.사유, AI검증: ep.AI검증.상태, AI검증사유: ep.AI검증.사유, 미처리: !!ep.AI검증.미처리,
    시험용: !!n.시험용, 중복후보: n.중복후보, 최초발견: n.최초발견?.시각, 원천: n.원천, 검증필요: n.검증필요,
  };
}

function 지표만들기({ 목록, 기관들, 실행들, 누락, 사용량, 모드, 지지난계획 }) {
  const 수집들 = 실행들.filter((r) => r.종류 === '수집' || r.종류 === '재확인');
  const 마지막수집 = 수집들[수집들.length - 1];
  const 활성 = 기관들.filter((k) => k.사용).length;
  const 호출들 = 사용량.filter((e) => e.이벤트 === '시작' && e.모드 === 모드);
  const 오늘 = 한국날짜(new Date());
  const 소요들 = 수집들.map((r) => r.지표?.소요ms).filter((x) => Number.isFinite(x));
  const 제외 = (사유) => 목록.filter((n) => n['제외·보존'].AI검증.사유 === 사유).length;
  return [
    { 이름: '검색 대상 기관 수', 값: `${활성}곳 (전체 ${기관들.length}곳)`, 종류: '측정' },
    { 이름: '점검 완료 기관 수', 값: 마지막수집 ? `${마지막수집.지표.완료} / ${마지막수집.지표.대상기관}곳 (마지막 점검)` : '아직 점검 전', 종류: '측정' },
    { 이름: '접속 실패 기관 수', 값: 마지막수집 ? `${마지막수집.지표.접속실패}곳 (자료 추출 실패 ${마지막수집.지표.추출실패}, 검증 필요 ${마지막수집.지표.검증필요})` : '아직 점검 전', 종류: '측정' },
    { 이름: '신규 발견 공고 수', 값: 마지막수집 ? `${마지막수집.지표.신규}건 (마지막 점검)` : '아직 점검 전', 종류: '측정' },
    { 이름: '공식 원문 검증 공고 수', 값: `${목록.filter((n) => n.검증상태 === '검증됨').length} / ${목록.length}건`, 종류: '측정' },
    { 이름: '중복 제거 공고 수', 값: `이미 있던 글로 판정 ${수집들.reduce((a, r) => a + (r.지표?.기존 || 0), 0)}건, 중복 후보 ${목록.filter((n) => n.중복후보).length}건`, 종류: '측정' },
    { 이름: '사후 발견 누락 공고 수', 값: `${누락.length}건`, 종류: '측정' },
    { 이름: '평균 검색 소요 시간', 값: 소요들.length ? `${Math.round(소요들.reduce((a, b) => a + b, 0) / 소요들.length)}ms (${소요들.length}회 평균)` : '기록 없음', 종류: '측정' },
    { 이름: 'AI 호출 횟수', 값: `오늘 ${호출들.filter((e) => 한국날짜(new Date(e.시각)) === 오늘).length}회 / 전체 ${호출들.length}회 (${모드 === 'mock' ? 'Mock 호출' : '실제 호출'})`, 종류: '측정' },
    { 이름: '입력·출력 토큰', 값: 모드 === 'mock' ? '해당 없음 (Mock은 토큰을 쓰지 않아요)' : '기록 없음', 종류: '조회 불가' },
    { 이름: '추정 API 비용', 값: '계산 불가', 종류: '조회 불가' },
    { 이름: 'AI 한도 잔여량', 값: '조회 불가 (한도 오류가 나야 알 수 있어요)', 종류: '조회 불가' },
    { 이름: '코드로 제외한 공고', 값: `인천 ${제외('코드판정-지역')}건, 마감 확정 ${제외('코드판정-마감확정')}건 (기록은 보존)`, 종류: '측정' },
    { 이름: 'AI 재검증을 생략한 공고', 값: `변경 없음 ${제외('변경없음')}건`, 종류: '측정' },
    ...(지지난계획 ? [{ 이름: '다음 검증의 예상 호출 수', 값: `${지지난계획.예상호출수}회 (입력 약 ${지지난계획.추정입력글자}자)`, 종류: '추정' }] : []),
  ];
}

function 개요만들기({ 목록, 기관들, 실행들, 누락, 사용량, 설정값, 모드, 지금, 계획 }) {
  const 요약들 = 목록.map((n) => 요약(n, 지금));
  const 오늘 = 한국날짜(지금);
  const 노출 = 요약들.filter((x) => x.노출);
  const 마감지남 = (x) => x.공고상태 === '접수 마감';
  const 신규 = 노출.filter((x) => x.최초발견 && 한국날짜(new Date(x.최초발견)) === 오늘);
  const 임박 = 노출.filter((x) => x.마감판정 === '확정' && !마감지남(x) && x.남은일수 !== null && x.남은일수 <= 설정값.마감임박일).sort((a, b) => a.남은일수 - b.남은일수);
  const 지원가능 = 노출.filter((x) => x.판정 === '적합' && x.검증상태 === '검증됨' && !마감지남(x));
  const 확인필요 = 노출.filter((x) => x.판정 === '확인 필요');
  const 다시확인 = 기관들.filter((k) => k.사용 && (!k.마지막점검 || 다시확인대상.includes(k.마지막점검.결과))).map((k) => ({ id: k.id, 이름: k.이름, 지역: k.지역, 결과: k.마지막점검?.결과 || '검색 미실행', 오류: k.마지막점검?.오류 || '아직 점검한 적이 없어요', HTTP상태: k.마지막점검?.HTTP상태 ?? null, 시험용: !!k.시험용 }));
  const 지원 = Object.fromEntries([...지원상태목록, '미지정'].map((s) => [s, 0]));
  for (const x of 노출) 지원[x.지원상태 || '미지정']++;
  return {
    기준시각: 지금.toISOString(), 설정: { 마감임박일: 설정값.마감임박일 },
    합계: { 전체: 요약들.length, 추천: 노출.length, 보관: 요약들.length - 노출.length, 미처리: 요약들.filter((x) => x.미처리).length, 중복후보: 요약들.filter((x) => x.중복후보).length, 검증대상: 요약들.filter((x) => x.AI검증 === '대상').length },
    오늘신규: 신규.slice(0, 20), 마감임박: 임박.slice(0, 20), 지원가능: 지원가능.slice(0, 20), 확인필요: 확인필요.slice(0, 30), 다시확인기관: 다시확인, 지원진행: 지원,
    주택그룹: 설정값.검색종류 === 'housing' ? ['플랫폼시티', '용인 생활권', '그 밖의 공고'].map(이름 => { const items = 노출.filter(x => x.주택?.그룹 === 이름); return { 이름, 합계: items.length, 목록: items.slice(0, 20) }; }) : null,
    최근실행: 실행들.slice(-8).reverse().map((r) => ({ id: r.id, 종류: r.종류, 시작: r.시작, 모드: r.모드, 중단이유: r.중단이유 || null, 지표: r.지표, AI호출: r.AI호출?.횟수 ?? 0, 재사용: r.AI호출?.재사용 ?? 0 })),
    지표: 지표만들기({ 목록, 기관들, 실행들, 누락, 사용량, 모드, 지지난계획: 계획 }),
    누락: 누락.slice(-10).reverse(),
  };
}

module.exports = { 요약, 개요만들기, 지원상태목록 };
